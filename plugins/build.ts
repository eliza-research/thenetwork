#!/usr/bin/env -S node --import=tsx
// Builds the SKILL.md snapshots in the two plugins from the one source, sites/skills/<name>/SKILL.md.
// Never edit a snapshot by hand: change the source, then run this. ChatGPT and Codex import the
// skills when the plugin is submitted and do not fetch them again, so a change needs a new plugin version.
//   node --import tsx --env-file-if-exists=.env plugins/build.ts           write plugins/openai/skills and plugins/claude/skills
//   node --import tsx --env-file-if-exists=.env plugins/build.ts --check   exit 1 if a snapshot differs from a fresh build (tests run this)
//
// The OpenAI plugin leaves out slop.date: OpenAI requires plugins that suit people aged 13-17
// (developers.openai.com/plugins/plugin-guidelines). Its copy of the hub skill is cut down to the
// other apps, and the build fails if "slop" or "dating" is left anywhere in plugins/openai.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { type Plugin, appOpenAiEndpointPath, endpointHost, endpointPath, openAiManifestApp, pluginEndpoint, pluginListsSkill, skillFor } from "../packages/core/src/generated/agentEntry.ts";
import { type AppKey, appKeys, brandFor, connectorEndpoint, openaiConnectorEndpoint } from "../packages/core/src/generated/brandIdentity.ts";
import { DEFAULT_BACKEND_ORIGIN, DEFAULT_TEXT_LINE } from "../sites/skills.config.ts";

const ROOT = import.meta.dirname;
const SOURCE = join(ROOT, "..", "sites", "skills");

/** Each skill name and the domain of its app (spec/brandIdentity.md:9). */
export const SITE: Record<string, string> = Object.fromEntries(appKeys.map(app => [skillFor(app), brandFor(app).domain]));
export function endpointUrl(plugin: Plugin, app: AppKey): string {
  const path = endpointPath(pluginEndpoint(plugin, app), app);
  if (path === "") throw new Error(`${plugin} lists ${skillFor(app)} but has no MCP endpoint for it`);
  return `https://${brandFor(endpointHost).domain}${path}`;
}

export const OPENAI_MCP_URL = endpointUrl("OpenAiPlugin", openAiManifestApp);

const openAiEndpointUrl = (app: AppKey) => {
  const path = appOpenAiEndpointPath(app);
  return path ? `https://${brandFor(endpointHost).domain}${path}` : "";
};

for (const app of appKeys) {
  if (endpointUrl("ClaudePlugin", app) !== connectorEndpoint(app) || openAiEndpointUrl(app) !== openaiConnectorEndpoint(app)) {
    throw new Error(`the connector endpoints of ${skillFor(app)} in spec/agentEntry.md and spec/brandIdentity.md differ`);
  }
}

/** The skills one plugin lists, in brand order, and the MCP URL of each (spec/agentEntry.md:9). */
function pluginSkills(plugin: Plugin): { skills: string[]; app: (skill: string) => AppKey; mcpUrl: (skill: string) => string } {
  const listed = appKeys.filter(app => pluginListsSkill(plugin, app));
  const urls = new Map(listed.map(app => [skillFor(app), endpointUrl(plugin, app)]));
  return {
    skills: [...urls.keys()],
    app: skill => {
      const app = listed.find(a => skillFor(a) === skill);
      if (app === undefined) throw new Error(`${plugin} does not list ${skill}`);
      return app;
    },
    mcpUrl: skill => {
      const url = urls.get(skill);
      if (url === undefined) throw new Error(`${plugin} does not list ${skill}`);
      return url;
    },
  };
}

export const PLUGINS = { openai: pluginSkills("OpenAiPlugin"), claude: pluginSkills("ClaudePlugin") };

const fill = (text: string, mcpUrl: string) =>
  text.replaceAll("{{BACKEND_ORIGIN}}", DEFAULT_BACKEND_ORIGIN).replaceAll("{{MCP_URL}}", mcpUrl).replaceAll("{{TEXT_LINE}}", DEFAULT_TEXT_LINE);

/** Remove slop.date from a skill for the OpenAI plugin: inline mentions, then whole table rows and list items. */
export function withoutSlop(md: string): string {
  const inline = md
    .replace(/slop\.date \(dating\), /g, "")
    .replace(/ntwrk\.party, slop\.date, /g, "ntwrk.party, ")
    .replace(/"leave slop\.date"/g, '"leave peon.biz"')
    .replace(/ Dating details never move\./g, "")
    .replace(/friends, dating or work/g, "friends or work");
  const out: string[] = [];
  const lines = inline.split("\n");
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!;
    if (line.startsWith("|") && /slop/i.test(line)) continue;
    if (/^- /.test(line)) {
      // A list item and its indented continuation lines.
      let j = i + 1;
      while (j < lines.length && /^ {2}\S/.test(lines[j]!)) j++;
      const item = lines.slice(i, j);
      if (item.some(l => /slop|dating/i.test(l))) { i = j - 1; continue; }
    }
    out.push(line);
  }
  return out.join("\n");
}

const OPENAI_SERVER_NAME = "the-network";

const openaiYaml = (skill: string, url: string) => `# Generated by plugins/build.ts. Do not edit.
dependencies:
  tools:
    - type: mcp
      value: ${serverName(skill)}
      description: The MCP endpoint of ${SITE[skill]}. app_info needs no sign-in. check_status and submit_profile need the person to sign in themselves in the browser.
      transport: streamable_http
      url: ${url}
`;

const serverName = (skill: string) => (skill === skillFor(openAiManifestApp) ? OPENAI_SERVER_NAME : skill);

export const claudeMcpJson = () => JSON.stringify({
  mcpServers: Object.fromEntries(PLUGINS.claude.skills.map(skill => [serverName(skill), { type: "http", url: PLUGINS.claude.mcpUrl(skill) }])),
}, null, 2) + "\n";

export const openaiMcpJson = () => JSON.stringify({
  $schema: "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json",
  mcpServers: { [OPENAI_SERVER_NAME]: { type: "streamable-http", url: OPENAI_MCP_URL } },
}, null, 2) + "\n";

export function build(): Map<string, string> {
  const files = new Map<string, string>();
  for (const [plugin, p] of Object.entries(PLUGINS)) {
    for (const skill of p.skills) {
      const src = readFileSync(join(SOURCE, skill, "SKILL.md"), "utf8");
      let text = fill(src, p.mcpUrl(skill));
      if (plugin === "openai") text = withoutSlop(text);
      if (text.includes("{{")) throw new Error(`${plugin}/${skill}: an unfilled {{placeholder}} is left`);
      if (plugin === "openai" && /slop|dating/i.test(text)) throw new Error(`openai/${skill}: slop.date is still mentioned; extend withoutSlop()`);
      const app = p.app(skill);
      const urls = [p.mcpUrl(skill)];
      const openAiUrl = openAiEndpointUrl(app);
      if (plugin === "claude" && openAiUrl) urls.push(openAiUrl);
      for (const url of urls) {
        if (!new RegExp(`${url.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?![\\w/])`).test(text)) throw new Error(`${plugin}/${skill}: the skill does not name its connector endpoint ${url} (spec/agentEntry.md)`);
      }
      files.set(join(plugin, "skills", skill, "SKILL.md"), text);
      if (plugin === "openai") files.set(join(plugin, "skills", skill, "agents", "openai.yaml"), openaiYaml(skill, p.mcpUrl(skill)));
    }
  }
  files.set(join("openai", "mcp.json"), openaiMcpJson());
  files.set(join("claude", ".mcp.json"), claudeMcpJson());
  return files;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const files = build();
  const stale: string[] = [];
  for (const [rel, text] of files) {
    const path = join(ROOT, rel);
    const cur = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (cur === text) continue;
    if (check) stale.push(rel);
    else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text); console.log(`wrote plugins/${rel}`); }
  }
  for (const plugin of Object.keys(PLUGINS)) {
    const dir = join(ROOT, plugin, "skills");
    const want = new Set(PLUGINS[plugin as keyof typeof PLUGINS].skills as readonly string[]);
    for (const d of existsSync(dir) ? readdirSync(dir) : []) if (!want.has(d)) stale.push(`${plugin}/skills/${d} (not in the plugin; delete it)`);
  }
  if (stale.length) { console.error(`stale snapshots (run node --import tsx --env-file-if-exists=.env plugins/build.ts):\n  ${stale.join("\n  ")}`); process.exit(1); }
  if (check) console.log("plugin skill snapshots are up to date");
}
