// Inlines core.ts in index.html, which must stay one file with no network access.
//   bun run tools/clef-label/build.ts           write the block
//   bun run tools/clef-label/build.ts --check   exit 1 when the block is stale
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as core from "./core.ts";

const CORE = join(import.meta.dir, "core.ts"), PAGE = join(import.meta.dir, "index.html");
const BEGIN = "// core.ts begin (generated by tools/clef-label/build.ts; do not edit)\n", END = "// core.ts end\n";

/** core.ts as plain script: the page has one inline script, so nothing is exported. */
export function coreBlock(): string {
  const js = new Bun.Transpiler({ loader: "ts", target: "browser" }).transformSync(readFileSync(CORE, "utf8"));
  const block = js.replace(/^export\s+\{[^}]*\};?\s*$/m, "").replace(/^export\s+/gm, "").trim();
  if (/^\s*(import|export)\b/m.test(block) || block.includes("</script")) throw new Error("core.ts cannot be inlined");
  for (const name of Object.keys(core)) if (!new RegExp(`\\bfunction ${name}\\b`).test(block)) throw new Error(`core.ts export ${name} is not inlined`);
  return block + "\n";
}

/** The page with the block in place. */
export function inlined(html: string): string {
  const from = html.indexOf(BEGIN), to = html.indexOf(END);
  if (from < 0 || to < from) throw new Error("index.html has no core.ts markers");
  return html.slice(0, from + BEGIN.length) + coreBlock() + html.slice(to);
}

if (import.meta.main) {
  const html = readFileSync(PAGE, "utf8"), next = inlined(html);
  if (process.argv.includes("--check")) {
    if (next !== html) { console.error("tools/clef-label/index.html is stale: run bun run tools/clef-label/build.ts"); process.exit(1); }
  } else writeFileSync(PAGE, next);
}
