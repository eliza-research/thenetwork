export function manifestSummary(): {
  total: number;
  bySuite: Record<SuiteName, number>;
  byPhase: Record<PhaseNumber, number>;
  byMode: Record<CaseMode, number>;
  byProbe: Record<ProbeKey, number>;
  credentialsCount: number;
} {
  const bySuite = Object.fromEntries(SUITE_NAMES.map(s => [s, 0])) as Record<SuiteName, number>;
  const byPhase = Object.fromEntries(PHASE_NUMBERS.map(p => [p, 0])) as Record<PhaseNumber, number>;
  const byMode: Record<CaseMode, number> = { "AUTO-LIVE": 0, "SEMI-AUTO": 0, MANUAL: 0 };
  const byProbe: Record<ProbeKey, number> = {
    journey_eval_live: 0,
    journey_eval_offline: 0,
    review_eval_live: 0,
    relay_eval_live: 0,
    clef_features_live: 0,
    llm_live_roundtrip: 0,
    http_staging_probe: 0,
    marketing_live_probe: 0,
    e2e_connector_probe: 0,
    security_suite_probe: 0,
    manual_checklist_probe: 0,
  };

  for (const c of LIVE_TEST_MANIFEST) {
    bySuite[c.suite] += 1;
    byPhase[c.phase] += 1;
    byMode[c.mode] += 1;
    byProbe[c.probeKey] += 1;
  }

  return {
    total: LIVE_TEST_MANIFEST.length,
    bySuite,
    byPhase,
    byMode,
    byProbe,
    credentialsCount: USER_CREDENTIAL_MANIFEST.length,
  };
}
